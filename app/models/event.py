"""Event model.

Every detection pushed by an edge device is persisted here. Key points:

- ``event_id`` is a string generated by the edge device and carries a **unique
  constraint**, giving DB-level idempotency: a retried/delayed push with the
  same ``event_id`` cannot create a duplicate row.
- ``detections``, ``snapshot``, and ``metadata`` are JSONB bags holding nested
  payload sections. ``event_type`` is a plain string here; the typed enum and
  validation live in the event-payload contract.
- ``event_timestamp`` comes from the device clock; ``received_timestamp`` is set
  server-side on ingestion (device clocks are not trusted for ordering).
"""

from __future__ import annotations

import datetime
import uuid

from sqlalchemy import DateTime, Float, ForeignKey, String
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base
from app.models.base import TimestampMixin, UUIDPrimaryKey


class Event(UUIDPrimaryKey, TimestampMixin, Base):
    __tablename__ = "events"

    event_id: Mapped[str] = mapped_column(String(255), nullable=False, unique=True)

    farm_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("farms.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    device_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("devices.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    event_type: Mapped[str] = mapped_column(String(64), nullable=False)
    confidence: Mapped[float | None] = mapped_column(Float, nullable=True)

    detections: Mapped[list | dict | None] = mapped_column(JSONB, nullable=True)
    snapshot: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    # ``metadata`` is reserved on the SQLAlchemy declarative base, so the Python
    # attribute is ``meta`` while the DB column stays ``metadata`` per the design.
    meta: Mapped[dict | None] = mapped_column("metadata", JSONB, nullable=True)

    event_timestamp: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    received_timestamp: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
